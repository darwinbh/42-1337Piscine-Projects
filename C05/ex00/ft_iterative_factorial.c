int	ft_iterative_factorial(int nb)
{
	int	j;

	if (nb == 0)
		return (1);
	if (nb < 0)
		return (0);
	j = nb;
	while (j != 1)
	{
		nb *= (j - 1);
		j--;
	}
	return (nb);
}
