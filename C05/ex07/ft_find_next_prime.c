int	ft_find_next_prime(int nb)
{
	int	i;

	if (nb < 2)
		nb = 2;
	i = 2;
	while (1)
	{
		while (i <= nb)
		{
			if (nb == i)
				return (nb);
			if (nb % i == 0)
				break ;
			i++;
		}
		i = 2;
		nb++;
	}
}
