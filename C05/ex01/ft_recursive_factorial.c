int	ft_recursive_factorial(int nb)
{
	int	i;

	i = nb;
	if (nb < 0)
		return (0);
	if (nb == 0)
		return (1);
	if (i != 1)
		nb *= ft_recursive_factorial(i - 1);
	return (nb);
}
